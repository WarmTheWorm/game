# The sound sets the level editor offers, each one a variation on the game's
# own. They are derived rather than hand-written, so a change to the root set
# carries through: run assets\editor\_sync.ps1 first, then this.
#
#   pwsh -NoProfile -File assets\editor\sounds\_generate.ps1
$ErrorActionPreference = 'Stop'

$root = Get-Content (Join-Path $PSScriptRoot 'default.json') -Raw | ConvertFrom-Json

# A def is a flat bag of numbers plus a wave name, so a variation is a rule per
# field rather than a rewrite of every noise.
function New-Set([string]$name, [string]$note, [hashtable]$waves, [double]$gain, [double]$decay, [double]$shake) {
  $out = [ordered]@{}
  foreach ($key in $root.sounds.PSObject.Properties.Name) {
    $def = $root.sounds.$key
    $copy = [ordered]@{}
    foreach ($field in $def.PSObject.Properties) { $copy[$field.Name] = $field.Value }
    # a track or a recorded clip has no shape to bend, so it is passed through
    if (-not $copy.Contains('wave')) { $out[$key] = $copy; continue }
    if ($waves.ContainsKey($copy.wave)) { $copy.wave = $waves[$copy.wave] }
    $copy.gain = [Math]::Round($copy.gain * $gain, 3)
    $copy.decay = [Math]::Round($copy.decay * $decay, 3)
    if ($copy.Contains('attack')) { $copy.attack = [Math]::Round($copy.attack * $decay, 3) }
    if ($copy.Contains('shake')) { $copy.shake = [int][Math]::Round($copy.shake * $shake) }
    if ($copy.Contains('noise')) {
      $copy.noise = [ordered]@{
        gain  = [Math]::Round($def.noise.gain * $gain, 3)
        decay = [Math]::Round($def.noise.decay * $decay, 3)
      }
    }
    $out[$key] = $copy
  }
  $doc = [ordered]@{ _comment = $note; sounds = $out }
  $path = Join-Path $PSScriptRoot $name
  $doc | ConvertTo-Json -Depth 8 | Set-Content $path -Encoding UTF8
  "{0,-14} {1,2} sounds  {2,6:N0} bytes" -f $name, $out.Count, (Get-Item $path).Length
}

# Softer: rounder waves, quieter, and every note given longer to fade.
New-Set 'soft.json' 'The game''s own sounds, rounded off and given room to ring. Generated by _generate.ps1.' `
  @{ square = 'triangle'; sawtooth = 'triangle' } 0.75 1.6 0.6

# Sharper: square everything, cut the tails short, buzz harder.
New-Set 'retro.json' 'The game''s own sounds as a handheld would have made them: square waves, short tails. Generated by _generate.ps1.' `
  @{ sine = 'square'; triangle = 'square'; sawtooth = 'square' } 1.0 0.6 1.4

# Recorded: a few ids swapped for struck-bell clips instead of one oscillator.
# Everything it leaves out keeps the sound it already had.
$clips = [ordered]@{
  _comment = 'Recorded one-shots in place of the synthesized coin, gem and unlock. Everything else is left to the root set. Generated by _generate.ps1.'
  sounds   = [ordered]@{
    coin   = [ordered]@{ src = 'clips/coin.wav';   gain = 0.5; shake = 12 }
    gem    = [ordered]@{ src = 'clips/gem.wav';    gain = 0.5; shake = 25 }
    unlock = [ordered]@{ src = 'clips/unlock.wav'; gain = 0.6; shake = 30 }
  }
}
$path = Join-Path $PSScriptRoot 'clips.json'
$clips | ConvertTo-Json -Depth 8 | Set-Content $path -Encoding UTF8
"{0,-14} {1,2} sounds  {2,6:N0} bytes" -f 'clips.json', $clips.sounds.Count, (Get-Item $path).Length
